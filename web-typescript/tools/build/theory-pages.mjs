// Where each 차시 starts in its unit's 이론서 (public/materials/theory-<단원>.pdf), for the lesson's
// "더 깊이: 이론서 p.N" link. Reads the PDFs with pdftotext (poppler-utils) and writes
// src/engine/education/theoryPages.gen.ts. Run after the theory PDFs are printed (tools/build/materials.mjs):
//   node tools/build/theory-pages.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const web = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const pages = {};
for (let unit = 1; unit <= 8; unit++) {
  const pdf = path.join(web, 'public', 'materials', `theory-${unit}.pdf`);
  const text = execFileSync('pdftotext', ['-layout', pdf, '-'], { encoding: 'utf8', maxBuffer: 64 << 20 });
  text.split('\f').forEach((page, i) => {
    // A 차시 starts on the page whose subtitle says where it sits in the unit: "… · 단원 안 2 / 4차시 · 50분".
    for (const m of page.matchAll(/단원 안 (\d+) \/ \d+차시/g)) {
      const id = `${unit}-${m[1]}`;
      if (!(id in pages)) pages[id] = i + 1;
    }
  });
}
const ids = Object.keys(pages).sort();
const body = ids.map((id) => `  '${id}': ${pages[id]},`).join('\n');
writeFileSync(
  path.join(web, 'src', 'engine', 'education', 'theoryPages.gen.ts'),
  `// Generated by tools/build/theory-pages.mjs from public/materials/theory-<단원>.pdf. Do not edit.\n` +
    `/** The page of its unit's 이론서 where each 차시 starts. */\n` +
    `export const THEORY_PAGE: Readonly<Record<string, number>> = {\n${body}\n};\n`,
);
console.log(`${ids.length} 차시:`, ids.map((id) => `${id}→p.${pages[id]}`).join(' '));
